# Conversão de tipos, coerção
# type convertion, typecasting, coercion
# é o ato de converter um tipo em outro
# tipos imutaveis e primitivos:
# str, int, Float, bool
print(1 + 1)
print('a' + 'b')
print(int('1'), type(int('1')))
print(int('1') + 1)
print(type(float('1.2') + 1))
print(bool(''))
print(str(11) + 'b')